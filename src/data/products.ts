function getSizesForProduct(gender: GenderCategory, category: string, index: number): SizeStock[] {
  if (gender === 'beauty' || gender === 'accessories') {
    return [{ size: 'One Size', stock: 18 }];
  }
  if (gender === 'footwear') {
    return [
      { size: 'UK 6', stock: index % 4 === 0 ? 0 : 7 },
      { size: 'UK 7', stock: 10 },
      { size: 'UK 8', stock: 14 },
      { size: 'UK 9', stock: 9 },
      { size: 'UK 10', stock: index % 3 === 0 ? 0 : 6 },
    ];
  }
  if (gender === 'kids') {
    return [
      { size: '4-5Y', stock: 8 },
      { size: '6-7Y', stock: 12 },
      { size: '8-9Y', stock: index % 5 === 0 ? 0 : 9 },
      { size: '10-11Y', stock: 5 },
    ];
  }
  if (category === 'trousers' || category === 'jeans') {
    return [
      { size: '28', stock: 6 },
      { size: '30', stock: 12 },
      { size: '32', stock: 14 },
      { size: '34', stock: 8 },
      { size: '36', stock: index % 3 === 0 ? 0 : 4 },
    ];
  }
  return [
    { size: 'XS', stock: index % 4 === 0 ? 0 : 5 },
    { size: 'S', stock: 11 },
    { size: 'M', stock: 16 },
    { size: 'L', stock: 10 },
    { size: 'XL', stock: 7 },
    { size: 'XXL', stock: index % 6 === 0 ? 0 : 4 },
  ];
}

